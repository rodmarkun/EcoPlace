ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
TASK_CONFIG = ROOT / "evolution/task/config.json"
CAMPAIGN_CONFIG = ROOT / "evolution/campaigns.json"
INITIAL = ROOT / "evolution/task/initial.py"
CANDIDATE_INDEX = HERE / "codex_candidates.json"
ARTIFACTS = HERE / "artifacts"


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _git(*args: str) -> str:
    return subprocess.run(
        ["git", *args],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()


class CodexBatchOperator:
    """Fresh-run one-shot batch generated by the active Codex workspace session."""

    name = "codex_workspace_batch_pilot"

    def __init__(self, candidates: list[dict[str, str]]) -> None:
        self._candidates = candidates
        self._next = 0

    def __call__(
        self,
        parent: Program,
        inspirations: tuple[Program, ...],
        rng: random.Random,
    ) -> ProposalOffspring:
        if not isinstance(rng, random.Random):
            raise TypeError("Codex pilot operator requires the runner-owned RNG")
        if self._next >= len(self._candidates):
            return ProposalOffspring(
                source=None,
                error="Codex pilot candidate batch exhausted",
                metadata={"operator": self.name, "api_costs_microusd": 0},
            )
        candidate = self._candidates[self._next]
        self._next += 1
        source = candidate["source"]
        return ProposalOffspring(
            source=source,
            metadata={
                "operator": self.name,
                "candidate_id": candidate["candidate_id"],
                "strategy": candidate["strategy"],
                "rationale": candidate["rationale"],
                "source_sha256": hashlib.sha256(source.encode()).hexdigest(),
                "generation_mode": "one-shot-batch-from-initial-policy",
                "baseline_contaminated": True,
                "parent_id_ignored_by_batch": parent.id,
                "inspiration_ids_ignored_by_batch": [item.id for item in inspirations],
                "api_costs_microusd": 0,
            },
        )


def _load_codex_candidates() -> tuple[dict[str, Any], list[dict[str, str]]]:
    raw = json.loads(CANDIDATE_INDEX.read_text())
    if (
        raw.get("schema") != "evolved-continuum-codex-pilot-candidates-v1"
        or raw.get("experiment_role") != "development-only-non-evidentiary"
        or len(raw.get("candidates", [])) != 6
    ):
        raise ValueError("Codex pilot candidate index has the wrong contract")
    initial = INITIAL.read_text()
    loaded = []
    for item in raw["candidates"]:
        path = HERE / item["path"]
        source = path.read_text()
        ps.Policy(source)
        validate_scoped_edit(initial, source)
        loaded.append(
            {
                "candidate_id": item["candidate_id"],
                "strategy": item["strategy"],
                "rationale": item["rationale"],
                "path": str(path.relative_to(HERE)),
                "source": source,
            }
        )
    return raw, loaded


def _arm_rows(runner: CampaignRunner) -> list[dict[str, Any]]:
    rows = []
    for event in runner.archive.events:
        if event["type"] != "candidate_completed":
            continue
        payload = event["payload"]
        ladder = payload.get("evaluation")
        evaluation = None if ladder is None else ladder.get("evaluation")
        fitness = None if evaluation is None else evaluation.get("fitness")
        rows.append(
            {
                "proposal_seq": payload["proposal_seq"],
                "candidate_id": payload["candidate_id"],
                "proposal_valid": payload["proposal"]["valid"],
                "proposal_operator": payload["proposal"].get("metadata", {}).get("operator"),
                "generated_candidate_id": payload["proposal"]
                .get("metadata", {})
                .get("candidate_id"),
                "strategy": payload["proposal"].get("metadata", {}).get("strategy"),
                "rung": (
                    None
                    if ladder is None
                    else ("L2" if ladder.get("promoted_to_l2") else "pre-L2")
                ),
                "feasible": None if fitness is None else fitness["feasible"],
                "normalized_energy": (
                    None if fitness is None else fitness["normalized_energy"]
                ),
                "infeasibility_vector": (
                    None if fitness is None else fitness["infeasibility_vector"]
                ),
                "entered_survivor": payload["decision"]["entered_survivor"],
                "cumulative_microwork": (
                    None
                    if payload.get("evaluator_work") is None
                    else payload["evaluator_work"]["cumulative_microwork"]
                ),
            }
        )
    return rows


def _best(rows: list[dict[str, Any]]) -> dict[str, Any]:
    eligible = [
        row
        for row in rows
        if row["rung"] == "L2"
        and row["feasible"] is True
        and row["normalized_energy"] is not None
    ]
    if not eligible:
        raise RuntimeError("pilot arm produced no L2-feasible candidate")
    return min(eligible, key=lambda row: (row["normalized_energy"], row["proposal_seq"]))


def _markdown(report: dict[str, Any]) -> str:
    comparison = report["comparison"]
    lines = [
        "# Codex placement-policy pilot report",
        "",
        "**Status:** development-only, non-evidentiary, baseline-contaminated.",
        "",
        "## Outcome",
        "",
        "| Arm | Valid / total | L2-feasible | Best sequence | "
        "Best normalized energy | Improvement vs initial |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for name in ("codex", "gp"):
        arm = report["arms"][name]
        lines.append(
            f"| {name} | {arm['valid_proposals']} / {arm['total_candidates']} | "
            f"{arm['l2_feasible']} | {arm['best']['proposal_seq']} | "
            f"{arm['best']['normalized_energy']:.9f} | "
            f"{arm['improvement_vs_initial_pct']:.2f}% |"
        )
    lines.extend(
        [
            "",
            f"Codex best versus GP best: **{comparison['codex_vs_gp_improvement_pct']:.2f}%** "
            "lower normalized energy.",
            "",
            f"Pilot signal: **{comparison['signal']}**.",
            "",
            "## Descriptive hand-written references",
            "",
            "| Policy | Feasible | Normalized energy |",
            "|---|---:|---:|",
        ]
    )
    for row in report["handwritten_references"]:
        lines.append(
            f"| {row['name']} | {str(row['feasible']).lower()} | "
            f"{row['normalized_energy']:.9f} |"
        )
    lines.extend(
        [
            "",
            "## Interpretation boundary",
            "",
            "- The scenario is the tiny checked-in development fixture; rebalancing is disabled.",
            "- The Codex batch was generated one-shot and ignored campaign-selected parents.",
            "- The active Codex session had already seen baseline code, so this is not "
            "an independent-discovery result.",
            "- No held-out data, preregistered gate, statistical inference, or "
            "confirmatory claim is involved.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    reused_existing_archives = ARTIFACTS.exists()
    if reused_existing_archives and not all(
        (ARTIFACTS / arm / "manifest.json").is_file() for arm in ("codex", "gp")
    ):
        raise FileExistsError(f"pilot artifact directory is incomplete: {ARTIFACTS}")
    raw_candidates, codex_candidates = _load_codex_candidates()
    task = load_task_evaluation_config(TASK_CONFIG)
    ladder = load_ladder_config(TASK_CONFIG)
    islands = load_islands_config(TASK_CONFIG)
    plan = dataclasses.replace(
        load_campaign_plan(CAMPAIGN_CONFIG),
        candidate_budget=7,
        max_operator_attempts=1,
        shared_numeric_probability=0.0,
    )
    definition = plan.campaigns[0]
    feedback = load_feedback_profiles(TASK_CONFIG)[plan.feedback_profile]
    initial_source = INITIAL.read_text()
    if reused_existing_archives:
        provenance = json.loads(
            (ARTIFACTS / "codex" / "manifest.json").read_text()
        )["provenance"]
    else:
        provenance = {
            "experiment_role": "development-only-non-evidentiary",
            "pilot": "pilot_codex_20260728",
            "git_head": _git("rev-parse", "HEAD"),
            "git_dirty_entries": _git(
                "status", "--porcelain=v1", "--untracked-files=all"
            ).splitlines(),
            "inputs": {
                "task_config_sha256": _sha256(TASK_CONFIG),
                "campaign_config_sha256": _sha256(CAMPAIGN_CONFIG),
                "initial_sha256": _sha256(INITIAL),
                "codex_candidate_index_sha256": _sha256(CANDIDATE_INDEX),
                "codex_candidate_source_sha256": {
                    item["candidate_id"]: hashlib.sha256(item["source"].encode()).hexdigest()
                    for item in codex_candidates
                },
            },
            "codex_generation": raw_candidates["generation"],
        }

    ARTIFACTS.mkdir(parents=True, exist_ok=True)
    started = time.perf_counter()
    codex_runner = CampaignRunner(
        definition=definition,
        plan=plan,
        arm="llm",
        operator=CodexBatchOperator(codex_candidates),
        initial_source=initial_source,
        task=task,
        ladder=ladder,
        islands=islands,
        feedback_profile=feedback,
        archive_dir=ARTIFACTS / "codex",
        provenance=provenance,
        run_purpose="determinism-smoke",
        evaluation_seed_mode="presealed-task",
    )
    codex_digest = codex_runner.run()
    codex_seconds = (
        None if reused_existing_archives else time.perf_counter() - started
    )

    started = time.perf_counter()
    gp_runner = CampaignRunner(
        definition=definition,
        plan=plan,
        arm="gp",
        operator=PlacementScriptGPOperator(),
        initial_source=initial_source,
        task=task,
        ladder=ladder,
        islands=islands,
        feedback_profile=feedback,
        archive_dir=ARTIFACTS / "gp",
        provenance=provenance,
        run_purpose="determinism-smoke",
        evaluation_seed_mode="presealed-task",
    )
    gp_digest = gp_runner.run()
    gp_seconds = None if reused_existing_archives else time.perf_counter() - started

    codex_rows = _arm_rows(codex_runner)
    gp_rows = _arm_rows(gp_runner)
    codex_best = _best(codex_rows)
    gp_best = _best(gp_rows)
    initial_energy = codex_rows[0]["normalized_energy"]
    if initial_energy is None:
        raise RuntimeError("initial policy has no normalized-energy record")

    handwritten = []
    for index, adapter in enumerate(all_handwritten()):
        result = adapter.evaluate(task, proposal_seq=10_000 + index)
        handwritten.append(
            {
                "name": adapter.name,
                "feasible": result.fitness.feasible,
                "normalized_energy": result.fitness.normalized_energy,
            }
        )

    def arm_summary(
        rows: list[dict[str, Any]],
        best: dict[str, Any],
        digest: str,
        seconds: float | None,
    ) -> dict[str, Any]:
        return {
            "archive_sha256": digest,
            "wall_seconds": seconds,
            "total_candidates": len(rows),
            "valid_proposals": sum(row["proposal_valid"] for row in rows),
            "l2_feasible": sum(
                row["rung"] == "L2" and row["feasible"] is True for row in rows
            ),
            "best": best,
            "improvement_vs_initial_pct": (
                100.0 * (initial_energy - best["normalized_energy"]) / initial_energy
            ),
            "rows": rows,
        }

    codex_vs_gp = (
        100.0
        * (gp_best["normalized_energy"] - codex_best["normalized_energy"])
        / gp_best["normalized_energy"]
    )
    useful = (
        codex_best["normalized_energy"] < initial_energy
        and codex_best["normalized_energy"] < gp_best["normalized_energy"]
    )
    report = {
        "schema": "evolved-continuum-codex-pilot-report-v1",
        "status": "DEVELOPMENT_COMPLETE",
        "acceptance_evidence": False,
        "confirmatory_evidence": False,
        "baseline_contaminated": True,
        "inputs": provenance,
        "comparison": {
            "initial_normalized_energy": initial_energy,
            "codex_best_normalized_energy": codex_best["normalized_energy"],
            "gp_best_normalized_energy": gp_best["normalized_energy"],
            "codex_vs_gp_improvement_pct": codex_vs_gp,
            "signal": "USEFUL_ENGINEERING_SIGNAL" if useful else "NO_USEFUL_SIGNAL",
        },
        "arms": {
            "codex": arm_summary(
                codex_rows, codex_best, codex_digest, codex_seconds
            ),
            "gp": arm_summary(gp_rows, gp_best, gp_digest, gp_seconds),
        },
        "handwritten_references": handwritten,
        "limitations": [
            "tiny checked-in development fixture",
            "rebalancing disabled",
            "one campaign root and six proposals per arm",
            "Codex proposals generated one-shot rather than adaptively",
            "Codex session had previously inspected baseline implementations",
            "no held-out data or statistical inference",
        ],
    }
    (HERE / "report.json").write_text(
        json.dumps(report, sort_keys=True, separators=(",", ":"), allow_nan=False) + "\n"
    )
    (HERE / "REPORT.md").write_text(_markdown(report))
    print(
        json.dumps(
            {
                "status": report["status"],
                "signal": report["comparison"]["signal"],
                "codex_best": codex_best["normalized_energy"],
                "gp_best": gp_best["normalized_energy"],
                "report": str(HERE / "REPORT.md"),
            },
            sort_keys=True,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
